/**
 * Ocean Quest Chronicles Project (see docs/references.md)
 * Models for the Sonar Challenge. The browser never talks to the Fish Game API directly:
 * our Express server fetches the puzzle and keeps the solution (interoperability + security).
 */
export interface PuzzleChallenge {
  puzzleId: string;
  question: string; // the aquarium picture as a data URI (from the Fish Game API, base64=yes)
  options?: number[]; // 3 options generated by server (one correct + two distractors)
}

export interface AnswerResult {
  correct: boolean;
  solution: number;       // revealed only after the answer has been checked
  points: number;         // awarded by the server
  runScore: number;
  chestsCollected: number;
}
